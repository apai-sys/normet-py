//! Sirois-Bottenheim mean directional-angle distances.
//!
//! `cluster_trajectories(metric="angle")` compares two back-trajectories by
//! the mean angle between their step vectors from the receptor (Sirois &
//! Bottenheim 1995), normalised by pi. The host builds the step vectors and
//! their norms (with `np.hypot`, passed in so the two backends share the
//! same bits), and this kernel fills the symmetric distance matrix over
//! trajectory pairs. The host's pair loop is O(n_traj^2 * n_steps) of small
//! numpy calls -- one call per array operation per pair -- so at a few
//! hundred trajectories it spends its time in call overhead; the kernel
//! keeps one buffer for the pair's angles and repeats the arithmetic.
//!
//! Parity is operation for operation: `denom = norm_i * norm_j`; a step is
//! valid when `denom > 1e-9`; the cosine is
//! `(vx_i * vx_j + vy_i * vy_j) / denom` clipped to `[-1, 1]` with NaN
//! propagating; the mean of `arccos(cos) / pi` over the valid steps uses
//! numpy's pairwise summation and divides once by the count; a pair with no
//! valid step is exactly zero. `f64::acos` is the platform libm's, which is
//! what `np.arccos` dispatches to for float64 on the platforms tested.

use std::fmt;

/// Input problems; all map to Python `ValueError` / R errors.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AngleError {
    /// The step vectors, norms or output matrix have inconsistent shapes.
    LengthMismatch,
}

impl fmt::Display for AngleError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::LengthMismatch => {
                write!(
                    f,
                    "step vectors, norms and the output matrix disagree in shape"
                )
            }
        }
    }
}

impl std::error::Error for AngleError {}

/// Sirois-Bottenheim distances for every trajectory pair, written to `out`.
///
/// `vx`/`vy`/`norms` are row-major `(n_traj, n_steps)`; `out` is row-major
/// `(n_traj, n_traj)` and receives the symmetric distance matrix with a zero
/// diagonal, which is what the host passes to `scipy`'s `squareform`
/// (`checks=False`). Steps are the trajectory points from the first
/// non-receptor sample on -- the host slices `dx[:, 1:]` before calling.
pub fn angle_distance_matrix(
    vx: &[f64],
    vy: &[f64],
    norms: &[f64],
    n_traj: usize,
    n_steps: usize,
    out: &mut [f64],
) -> Result<(), AngleError> {
    let Some(total) = n_traj.checked_mul(n_steps) else {
        return Err(AngleError::LengthMismatch);
    };
    if vx.len() != total
        || vy.len() != total
        || norms.len() != total
        || out.len() != n_traj * n_traj
    {
        return Err(AngleError::LengthMismatch);
    }

    let mut angles: Vec<f64> = Vec::with_capacity(n_steps);
    for i in 0..n_traj {
        out[i * n_traj + i] = 0.0;
        let row_i = i * n_steps;
        for j in (i + 1)..n_traj {
            let row_j = j * n_steps;
            angles.clear();
            for s in 0..n_steps {
                let denom = norms[row_i + s] * norms[row_j + s];
                if denom > 1e-9 {
                    // NaN propagates through the clamp, as np.clip does.
                    let cos_t = ((vx[row_i + s] * vx[row_j + s] + vy[row_i + s] * vy[row_j + s])
                        / denom)
                        .clamp(-1.0, 1.0);
                    angles.push(cos_t.acos() / std::f64::consts::PI);
                }
            }
            let d = if angles.is_empty() {
                0.0
            } else {
                crate::crps::pairwise_sum(&angles) / angles.len() as f64
            };
            out[i * n_traj + j] = d;
            out[j * n_traj + i] = d;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    // Values generated by the host's numpy block on these inputs.
    #[test]
    fn matrix_matches_the_host_loop() {
        let vx: [f64; 6] = [1.0, 2.0, -1.0, 0.5, 0.0, 1.5];
        let vy: [f64; 6] = [0.0, 1.0, 1.0, 1.0, 0.0, -2.0];
        let norms: Vec<f64> = vx
            .iter()
            .zip(vy.iter())
            .map(|(a, b)| (*a).hypot(*b))
            .collect();
        let mut out = vec![0.0; 9];
        angle_distance_matrix(&vx, &vy, &norms, 3, 2, &mut out).expect("shapes");
        assert_eq!(out[1], 0.477_416_382_349_566_8);
        assert_eq!(out[2], 0.442_750_852_951_299_8);
        assert_eq!(out[5], 0.647_583_617_650_433_3);
        assert_eq!(out[3], out[1]);
        assert_eq!(out[6], out[2]);
        assert_eq!(out[7], out[5]);
        assert_eq!((out[0], out[4], out[8]), (0.0, 0.0, 0.0));
    }

    #[test]
    fn zero_steps_give_zero_distance() {
        let vx = [0.0, 0.0, 0.0, 0.0];
        let vy = [0.0, 0.0, 0.0, 0.0];
        let norms = [0.0, 0.0, 0.0, 0.0];
        let mut out = vec![0.0; 4];
        angle_distance_matrix(&vx, &vy, &norms, 2, 2, &mut out).expect("shapes");
        assert_eq!(out, [0.0, 0.0, 0.0, 0.0]);
    }

    #[test]
    fn a_pair_with_no_valid_step_is_zero_even_with_nan_steps() {
        let vx = [f64::NAN, 1.0, f64::NAN, 2.0];
        let vy = [f64::NAN, 0.0, f64::NAN, 0.0];
        let norms = [f64::NAN, 1.0, f64::NAN, 2.0];
        let mut out = vec![0.0; 4];
        angle_distance_matrix(&vx, &vy, &norms, 2, 2, &mut out).expect("shapes");
        // Step 0 has denom NaN (invalid); step 1 is a valid and identical
        // direction, so the pair's distance is exactly zero.
        assert_eq!(out[1], 0.0);
    }

    #[test]
    fn errors() {
        let ok = [1.0, 0.0];
        let mut out = vec![0.0; 4];
        assert_eq!(
            angle_distance_matrix(&[1.0], &ok, &ok, 2, 1, &mut out),
            Err(AngleError::LengthMismatch)
        );
        assert_eq!(
            angle_distance_matrix(&ok, &ok, &ok, 2, 1, &mut [0.0; 3]),
            Err(AngleError::LengthMismatch)
        );
    }
}
